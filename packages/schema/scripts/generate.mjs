#!/usr/bin/env node
// Generates TypeScript types from the Pydantic-exported JSON Schema.
// Input:  generated/building-model.schema.json   (written by `pnpm schema` from the API)
// Output: src/generated/building-model.ts
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "generated", "building-model.schema.json");
const outPath = join(root, "src", "generated", "building-model.ts");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const ts = await compile(schema, "BuildingModel", {
  bannerComment:
    "/* GENERATED by packages/schema/scripts/generate.mjs from the Pydantic BuildingModel.\n" +
    " * Do not edit by hand - run `pnpm schema` from the repo root. */",
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  unreachableDefinitions: true,
  format: true,
  style: { printWidth: 100, trailingComma: "all" },
});
await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, ts.replace(/\r\n/g, "\n"), "utf8");
console.log(`wrote ${outPath}`);
